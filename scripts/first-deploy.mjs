import { randomBytes } from 'node:crypto';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const target = process.argv[2];
if (target !== 'staging' && target !== 'production') {
  console.error('Usage: node scripts/first-deploy.mjs <staging|production>');
  process.exit(2);
}

const verify = spawnSync(process.execPath, ['scripts/deploy-verify.mjs', target], { cwd: root, stdio: 'inherit' });
if (verify.status !== 0) process.exit(verify.status ?? 1);

const migrated = spawnSync(process.execPath, ['scripts/apply-registry-migrations.mjs', target], { cwd: root, stdio: 'inherit', env: process.env, shell: false });
if (migrated.status !== 0) process.exit(migrated.status ?? 1);

for (const script of ['scripts/build.mjs','scripts/inspect-build.mjs']) {
  const built = spawnSync(process.execPath, [script], { cwd: root, stdio: 'inherit', env: process.env, shell: false });
  if (built.status !== 0) process.exit(built.status ?? 1);
}

// Cloudflare `wrangler secret put` is itself a deployment action. For a first
// deployment, upload the required secret alongside the audited code instead so
// there is no surprise intermediate Worker version. The temporary file lives
// outside the project and is removed in a finally block.
const tempDir = await mkdtemp(path.join(os.tmpdir(), 'cosmic-first-deploy-'));
const secretsFile = path.join(tempDir, 'secrets.json');
const secret = randomBytes(32).toString('base64url');

try {
  await writeFile(secretsFile, JSON.stringify({ BYOK_SESSION_MASTER_KEY_CURRENT: secret }), { mode: 0o600 });
  const result = spawnSync(process.execPath, ['scripts/wrangler-invoke.mjs', 'deploy', '--strict', '--env', target, '--secrets-file', secretsFile], {
    cwd: root,
    stdio: 'inherit',
    env: process.env,
    shell: false
  });
  if (result.status !== 0) process.exitCode = result.status ?? 1;
} finally {
  await rm(tempDir, { recursive: true, force: true });
}

if (!process.exitCode) {
  console.log(`First ${target} deployment completed. The generated BYOK master key was not printed and the temporary secrets file was removed.`);
}
